-- =====================================================================
-- REPORTE 1. INVENTARIO X CATEGORIA
-- Inventario global = unidades compradas - unidades vendidas.
-- VALOR = inventario actual * precio de venta del producto.
--
-- Se calcula de forma global porque el Excel de COMPRAS no incluye ID_LOCAL,
-- por lo que no existe una distribucion confiable de las compras por local.
-- =====================================================================

WITH COMPRAS_PRODUCTO AS (
    SELECT PRODUCTO_ID_Producto,
           SUM(Cantidad) AS CANTIDAD_COMPRADA
    FROM DETALLE_COMPRA
    GROUP BY PRODUCTO_ID_Producto
),
VENTAS_PRODUCTO AS (
    SELECT PRODUCTO_ID_Producto,
           SUM(Cantidad) AS CANTIDAD_VENDIDA
    FROM DETALLE_VENTA
    GROUP BY PRODUCTO_ID_Producto
),
INVENTARIO AS (
    SELECT c.ID_Categoria,
           c.Nombre_Categoria AS CATEGORIA,
           p.ID_Producto,
           p.Nombre_Producto AS PRODUCTO,
           NVL(cp.CANTIDAD_COMPRADA, 0)
             - NVL(vp.CANTIDAD_VENDIDA, 0) AS TOTAL,
           (
               NVL(cp.CANTIDAD_COMPRADA, 0)
               - NVL(vp.CANTIDAD_VENDIDA, 0)
           ) * p.Precio_Venta AS VALOR
    FROM CATEGORIA c
    JOIN PRODUCTO p
      ON p.CATEGORIA_ID_Categoria = c.ID_Categoria
    LEFT JOIN COMPRAS_PRODUCTO cp
      ON cp.PRODUCTO_ID_Producto = p.ID_Producto
    LEFT JOIN VENTAS_PRODUCTO vp
      ON vp.PRODUCTO_ID_Producto = p.ID_Producto
),
ORDENADO AS (
    SELECT i.*,
           ROW_NUMBER() OVER (
               PARTITION BY ID_Categoria
               ORDER BY PRODUCTO
           ) AS NUM_FILA_CATEGORIA
    FROM INVENTARIO i
)
SELECT CATEGORIA,
       PRODUCTO,
       TOTAL,
       VALOR
FROM (
    SELECT CASE
               WHEN NUM_FILA_CATEGORIA = 1 THEN CATEGORIA
           END AS CATEGORIA,
           PRODUCTO,
           TOTAL,
           VALOR,
           ID_Categoria AS ORDEN_CATEGORIA,
           1 AS ORDEN_TIPO,
           ID_Producto AS ORDEN_PRODUCTO
    FROM ORDENADO

    UNION ALL

    SELECT 'TOTAL GENERAL',
           NULL,
           SUM(TOTAL),
           SUM(VALOR),
           999999,
           2,
           999999
    FROM INVENTARIO
)
ORDER BY ORDEN_CATEGORIA,
         ORDEN_TIPO,
         ORDEN_PRODUCTO;

