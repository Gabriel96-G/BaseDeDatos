-- VALOR TOTAL   = 420200050


-- =====================================================================
-- REPORTE 2. VENTAS X CLIENTES
-- Una fila por factura de venta.
-- =====================================================================

SELECT TO_CHAR(v.Fecha_Venta, 'DD/MM/YYYY') AS FECHA,
       c.Nombre || ' ' || c.Apellidos AS CLIENTE,
       SUM(dv.Cantidad * dv.Precio_Unitario) AS TOTAL_VENTA
FROM VENTA v
JOIN CLIENTE c
  ON c.ID_Cliente = v.CLIENTE_ID_Cliente
JOIN DETALLE_VENTA dv
  ON dv.VENTA_ID_Venta = v.ID_Venta
WHERE UPPER(v.Estado) <> 'ANULADA'
GROUP BY v.ID_Venta,
         v.Fecha_Venta,
         c.Nombre,
         c.Apellidos
ORDER BY v.Fecha_Venta,
         c.Apellidos,
         c.Nombre;

