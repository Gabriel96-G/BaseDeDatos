-- Total general = 13214850


-- =====================================================================
-- REPORTE 3. COMPRAS
-- Una fila por combinacion Producto-Proveedor.
-- CANTIDAD = cantidad registrada en la compra mas reciente.
-- FECHA_ULTIMA_COMPRA = fecha de esa misma compra.
-- =====================================================================

SELECT PRODUCTO,
       PROVEEDOR,
       CANTIDAD,
       FECHA_ULTIMA_COMPRA
FROM (
    SELECT p.Nombre_Producto AS PRODUCTO,
           pr.Nombre_Proveedor AS PROVEEDOR,
           dc.Cantidad AS CANTIDAD,
           TO_CHAR(c.Fecha_Compra, 'DD/MM/YYYY') AS FECHA_ULTIMA_COMPRA,
           ROW_NUMBER() OVER (
               PARTITION BY p.ID_Producto, pr.ID_Proveedor
               ORDER BY c.Fecha_Compra DESC, c.ID_Compra DESC
           ) AS RN
    FROM COMPRA c
    JOIN DETALLE_COMPRA dc
      ON dc.COMPRA_ID_Compra = c.ID_Compra
    JOIN PRODUCTO p
      ON p.ID_Producto = dc.PRODUCTO_ID_Producto
    JOIN PROVEEDOR pr
      ON pr.ID_Proveedor = c.PROVEEDOR_ID_Proveedor
    WHERE UPPER(c.Estado) <> 'ANULADA'
)
WHERE RN = 1
ORDER BY PRODUCTO,
         PROVEEDOR;

